struct SwapChainBuffer {
  AHardwareBuffer*          hardwareBuffer = nullptr;
  wgpu::SharedTextureMemory sharedTextureMemory = nullptr;
  wgpu::Texture             texture = nullptr;
  int                       releaseFenceFd = -1;
  bool                      isInitialized = false;
};

struct SwapChain {
  wgpu::Device        device = nullptr;
  ANativeWindow*      window = nullptr;
  ASurfaceControl*    surfaceControl = nullptr;
  uint32_t            width = 0;
  uint32_t            height = 0;
  wgpu::TextureFormat format = wgpu::TextureFormat::Undefined;

  static constexpr size_t kBufferCount = 3;
  SwapChainBuffer         buffers[kBufferCount];
  uint32_t                currentIndex = 0;
};

static void InitSwapChainBuffers(SwapChain* swapChain) {
  for (size_t i = 0; i < SwapChain::kBufferCount; ++i) {
    auto& b = swapChain->buffers[i];

    AHardwareBuffer_Desc desc = {};
    desc.width = swapChain->width;
    desc.height = swapChain->height;
    desc.layers = 1;
    desc.format = (swapChain->format == wgpu::TextureFormat::RGBA16Float)
                      ? AHARDWAREBUFFER_FORMAT_R16G16B16A16_FLOAT
                      : AHARDWAREBUFFER_FORMAT_R8G8B8A8_UNORM;
    desc.usage = AHARDWAREBUFFER_USAGE_GPU_SAMPLED_IMAGE | AHARDWAREBUFFER_USAGE_GPU_COLOR_OUTPUT |
                 AHARDWAREBUFFER_USAGE_COMPOSER_OVERLAY;

    if (AHardwareBuffer_allocate(&desc, &b.hardwareBuffer) != 0) {
      LOGV("Failed to allocate AHardwareBuffer");
      continue;
    }

    wgpu::SharedTextureMemoryAHardwareBufferDescriptor ahbDesc = {};
    ahbDesc.handle = b.hardwareBuffer;

    wgpu::SharedTextureMemoryDescriptor stmDesc = {};
    stmDesc.nextInChain = &ahbDesc;

    b.sharedTextureMemory = swapChain->device.ImportSharedTextureMemory(&stmDesc);
    if (!b.sharedTextureMemory) {
      LOGV("Failed to import SharedTextureMemory");
      continue;
    }

    b.texture = b.sharedTextureMemory.CreateTexture();
    b.releaseFenceFd = -1;
    b.isInitialized = false;
  }
}

static void FreeSwapChainBuffers(SwapChain* swapChain) {
  for (size_t i = 0; i < SwapChain::kBufferCount; ++i) {
    auto& b = swapChain->buffers[i];
    if (b.releaseFenceFd >= 0) {
      close(b.releaseFenceFd);
      b.releaseFenceFd = -1;
    }
    b.texture = nullptr;
    b.sharedTextureMemory = nullptr;
    if (b.hardwareBuffer) {
      AHardwareBuffer_release(b.hardwareBuffer);
      b.hardwareBuffer = nullptr;
    }
    b.isInitialized = false;
  }
}

__attribute__((availability(android, introduced = 29))) SwapChain*
SwapChain_SwapChain(int qualifiers, Type* format, Device* device, Window* window) {
  auto* swapChain = new SwapChain();
  swapChain->device = device->device;
  swapChain->window = window->window;
  swapChain->width = ANativeWindow_getWidth(window->window);
  swapChain->height = ANativeWindow_getHeight(window->window);
  swapChain->format = ToDawnTextureFormat(format);
  swapChain->currentIndex = 0;

  swapChain->surfaceControl =
      ASurfaceControl_createFromWindow(window->window, "Toucan HDR SurfaceControl");

  ASurfaceTransaction* transaction = ASurfaceTransaction_create();
  ASurfaceTransaction_setVisibility(transaction, swapChain->surfaceControl,
                                    ASURFACE_TRANSACTION_VISIBILITY_SHOW);
  ARect crop = {0, 0, static_cast<int32_t>(swapChain->width),
                static_cast<int32_t>(swapChain->height)};
  ARect frame = {0, 0, static_cast<int32_t>(swapChain->width),
                 static_cast<int32_t>(swapChain->height)};
  ASurfaceTransaction_setGeometry(transaction, swapChain->surfaceControl, crop, frame, 0);
  ASurfaceTransaction_apply(transaction);
  ASurfaceTransaction_delete(transaction);

  InitSwapChainBuffers(swapChain);
  return swapChain;
}

Texture2D* SwapChain_GetCurrentTexture(SwapChain* swapChain) {
  auto& b = swapChain->buffers[swapChain->currentIndex];

  wgpu::SharedTextureMemoryBeginAccessDescriptor beginDesc = {};
  beginDesc.concurrentRead = false;
  beginDesc.initialized = b.isInitialized;

  wgpu::SharedFence fence = nullptr;
  if (b.releaseFenceFd >= 0) {
    wgpu::SharedFenceSyncFDDescriptor syncFdDesc = {};
    syncFdDesc.handle = b.releaseFenceFd;

    wgpu::SharedFenceDescriptor fenceDesc = {};
    fenceDesc.nextInChain = &syncFdDesc;

    fence = swapChain->device.ImportSharedFence(&fenceDesc);
    if (fence) {
      beginDesc.fenceCount = 1;
      beginDesc.fences = &fence;
    }
    close(b.releaseFenceFd);
    b.releaseFenceFd = -1;
  }

  wgpu::SharedTextureMemoryVkImageLayoutBeginState vkBeginState = {};
  wgpu::AdapterInfo                                adapterInfo;
  swapChain->device.GetAdapterInfo(&adapterInfo);
  if (adapterInfo.backendType == wgpu::BackendType::Vulkan) {
    vkBeginState.oldLayout = b.isInitialized ? VK_IMAGE_LAYOUT_GENERAL : VK_IMAGE_LAYOUT_UNDEFINED;
    vkBeginState.newLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    beginDesc.nextInChain = &vkBeginState;
  }

  b.sharedTextureMemory.BeginAccess(b.texture, &beginDesc);

  return new Texture2D(b.texture, b.texture.CreateView());
}

__attribute__((availability(android, introduced = 29))) void SwapChain_Present(
    SwapChain* swapChain) {
  auto& b = swapChain->buffers[swapChain->currentIndex];

  wgpu::SharedTextureMemoryEndAccessState        endState = {};
  wgpu::SharedTextureMemoryVkImageLayoutEndState vkEndState = {};
  wgpu::AdapterInfo                              adapterInfo;
  swapChain->device.GetAdapterInfo(&adapterInfo);
  if (adapterInfo.backendType == wgpu::BackendType::Vulkan) {
    vkEndState.oldLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    vkEndState.newLayout = VK_IMAGE_LAYOUT_GENERAL;
    endState.nextInChain = &vkEndState;
  }

  wgpu::Status status = b.sharedTextureMemory.EndAccess(b.texture, &endState);
  b.isInitialized = true;
  int acquireFenceFd = -1;

  if (status == wgpu::Status::Success && endState.fenceCount > 0) {
    wgpu::SharedFence                 cFence = endState.fences[0];
    wgpu::SharedFenceExportInfo       exportInfo = {};
    wgpu::SharedFenceSyncFDExportInfo syncFdExportInfo = {};
    exportInfo.nextInChain = &syncFdExportInfo;

    cFence.ExportInfo(&exportInfo);
    int fd = syncFdExportInfo.handle;
    if (fd >= 0) { acquireFenceFd = dup(fd); }
  }

  ASurfaceTransaction* transaction = ASurfaceTransaction_create();
  ASurfaceTransaction_setBuffer(transaction, swapChain->surfaceControl, b.hardwareBuffer,
                                acquireFenceFd);
  ASurfaceTransaction_setVisibility(transaction, swapChain->surfaceControl,
                                    ASURFACE_TRANSACTION_VISIBILITY_SHOW);
  ARect crop = {0, 0, static_cast<int32_t>(swapChain->width),
                static_cast<int32_t>(swapChain->height)};
  ARect frame = {0, 0, static_cast<int32_t>(swapChain->width),
                 static_cast<int32_t>(swapChain->height)};
  ASurfaceTransaction_setGeometry(transaction, swapChain->surfaceControl, crop, frame, 0);

  enum ADataSpace dataSpace = (swapChain->format == wgpu::TextureFormat::RGBA16Float)
                                  ? ADATASPACE_SCRGB_LINEAR
                                  : ADATASPACE_SRGB;
  ASurfaceTransaction_setBufferDataSpace(transaction, swapChain->surfaceControl, dataSpace);

  if (swapChain->format == wgpu::TextureFormat::RGBA16Float) {
    ASurfaceTransaction_setExtendedRangeBrightness(transaction, swapChain->surfaceControl, 5.0f,
                                                   5.0f);
  }

  ASurfaceTransaction_apply(transaction);
  ASurfaceTransaction_delete(transaction);

  swapChain->currentIndex = (swapChain->currentIndex + 1) % SwapChain::kBufferCount;
}

void SwapChain_Resize(SwapChain* swapChain, const uint32_t* size) {
  swapChain->width = size[0];
  swapChain->height = size[1];
  FreeSwapChainBuffers(swapChain);
  InitSwapChainBuffers(swapChain);
  swapChain->currentIndex = 0;
}

__attribute__((availability(android, introduced = 29))) void SwapChain_Destroy(SwapChain* This) {
  FreeSwapChainBuffers(This);
  if (This->surfaceControl) {
    ASurfaceControl_release(This->surfaceControl);
    This->surfaceControl = nullptr;
  }
  delete This;
}

double System_GetCurrentTime() {
  struct timeval now;

  gettimeofday(&now, NULL);
  return static_cast<double>(now.tv_sec) + static_cast<double>(now.tv_usec) / 1000000.0;
}

