Device* Device_Device() {
  wgpu::DeviceDescriptor desc;

  static constexpr auto kRequiredFeatures = std::array{
      wgpu::FeatureName::SharedTextureMemoryAHardwareBuffer,
      wgpu::FeatureName::SharedFenceSyncFD,
  };
  desc.requiredFeatureCount = kRequiredFeatures.size();
  desc.requiredFeatures = kRequiredFeatures.data();

  desc.SetUncapturedErrorCallback(
      [](const wgpu::Device&, wgpu::ErrorType type, wgpu::StringView message) {
        LOGV("WebGPU Error:\n%s\n", message.data);
      });

  wgpu::Device device = CreateDawnDevice(wgpu::BackendType::Vulkan, &desc);
  if (!device) { return nullptr; }
  return new Device(device);
}

